"""The executive summary: three status cards, an overall status, key messages and headroom.

What a CRO or treasurer reads first. Every word is built from figures the dashboard already
shows (riskplatform.dashboard.data); nothing here calculates a risk number, and no text is
generated by a model. No Streamlit, so it is tested on its own (tests/test_executive.py).

Status rules, per rulebook (the one chosen in the sidebar):
- Liquidity: red if any LCR or NSFR limit is in breach or a regulatory minimum is missed, amber
  if any is at warning, else green.
- Interest rate risk: red if the EVE limit is in breach or the entity or group is an IRRBB
  outlier, amber if the EVE limit is at warning, else green.
- Early warnings: amber if any indicator is in alert, else green. An early warning is a signal,
  not a limit, so it never turns a card red on its own.
- Overall: the worst of the three.
Levels: every entity and the group (the levels the limits apply to).
"""

from dataclasses import dataclass

import duckdb
import pandas as pd

from riskplatform.dashboard import data

GREEN, AMBER, RED = "green", "amber", "red"
ORDER = [GREEN, AMBER, RED]
LIMIT_LABEL = {"lcr": "LCR", "nsfr": "NSFR", "eve_tier1": "EVE loss / Tier 1"}
LIQUIDITY, RATES = ("lcr", "nsfr"), ("eve_tier1",)


@dataclass(frozen=True)
class Card:
    area: str
    status: str  # green, amber or red
    reason: str  # one line, with the figure behind the status


def _worst(statuses) -> str:
    return max(statuses, key=ORDER.index, default=GREEN)


def _pct(value: float) -> str:
    return f"{value:.1%}"


def _limit(value: float) -> str:
    """A limit as executives read it: 15%, 110% (a whole number when it is one)."""
    return f"{value:.0%}" if round(value * 100, 6).is_integer() else f"{value:.1%}"


def _from_limits(table: pd.DataFrame) -> str:
    if (table["status"] == "breach").any():
        return RED
    return AMBER if (table["status"] == "warning").any() else GREEN


def liquidity_card(limits: pd.DataFrame, minimum_missed: bool) -> Card:
    rows = limits[limits["limit_name"].isin(LIQUIDITY)]
    status = RED if minimum_missed else _from_limits(rows)
    lcr = rows[rows["limit_name"] == "lcr"].nsmallest(1, "actual").iloc[0]
    nsfr = rows[rows["limit_name"] == "nsfr"].nsmallest(1, "actual").iloc[0]
    reason = (
        f"Lowest LCR {_pct(lcr['actual'])} ({lcr['who']}), lowest NSFR {_pct(nsfr['actual'])} "
        f"({nsfr['who']}); limits {_limit(lcr['limit_value'])} and {_limit(nsfr['limit_value'])}"
    )
    if minimum_missed:
        reason = "A regulatory minimum is missed. " + reason
    return Card("Liquidity", status, reason)


def rates_card(limits: pd.DataFrame, outliers: pd.DataFrame) -> Card:
    rows = limits[limits["limit_name"].isin(RATES)]
    flagged = list(outliers.loc[outliers["outlier"], "who"])
    status = RED if flagged else _from_limits(rows)
    worst = rows.nlargest(1, "actual").iloc[0]
    reason = (
        f"Highest EVE loss {_pct(worst['actual'])} of Tier 1 ({worst['who']}) against a "
        f"{_limit(worst['limit_value'])} limit"
    )
    if flagged:
        reason += f"; IRRBB outlier: {', '.join(flagged)}"
    return Card("Interest rate risk", status, reason)


def early_warning_card(indicators: pd.DataFrame) -> Card:
    alerts = indicators[indicators["status"] == "alert"]
    if alerts.empty:
        return Card("Early warnings", GREEN, "No indicator in alert")
    who = sorted(set(alerts["who"]))
    return Card("Early warnings", AMBER, f"{len(alerts)} in alert ({', '.join(who)})")


def cards(con: duckdb.DuckDBPyConnection, regime: str) -> list[Card]:
    """The three status cards for one rulebook."""
    limits = data.limit_status(con, regime)
    minimum_missed = _minimum_missed(con, regime)
    return [
        liquidity_card(limits, minimum_missed),
        rates_card(limits, data.eve_against_tier1(con, regime)),
        early_warning_card(data.early_warning(con, regime)),
    ]


def _minimum_missed(con: duckdb.DuckDBPyConnection, regime: str) -> bool:
    """True if any entity or group LCR or NSFR misses its regulatory minimum on the latest date."""
    sql = """
        SELECT count(*) FROM {view}
        WHERE regime = ? AND level IN ('entity', 'group') AND meets_minimum = false
          AND date = (SELECT max(date) FROM {view})
    """
    return any(con.execute(sql.format(view=v), [regime]).fetchone()[0] for v in ("lcr", "nsfr"))


def overall(card_list: list[Card]) -> str:
    return _worst(card.status for card in card_list)


def key_messages(con: duckdb.DuckDBPyConnection, regime: str, limit: int = 5) -> list[str]:
    """Up to `limit` plain sentences, most severe first, each built from the figures."""
    limits = data.limit_status(con, regime)
    previous, _ = data.compared_dates(con)
    messages = []
    for _, row in limits[limits["status"] == "breach"].iterrows():
        since = "new today" if row["movement"] == "new" else (
            f"unchanged since {previous:%d %b}" if previous is not None else "")  # fmt: skip
        word = "cap" if row["kind"] == "cap" else "floor"
        messages.append(
            f"{row['who']} breaches its {LIMIT_LABEL[row['limit_name']]} limit: "
            f"{_pct(row['actual'])} against a {_limit(row['limit_value'])} {word}"
            + (f", {since}." if since else ".")
        )
    warnings = limits[limits["status"] == "warning"].sort_values("utilisation", ascending=False)
    if not warnings.empty:
        closest = warnings.iloc[0]
        messages.append(
            f"{len(warnings)} limit{'s are' if len(warnings) > 1 else ' is'} at warning; the "
            f"closest is {closest['who']} {LIMIT_LABEL[closest['limit_name']]} at "
            f"{closest['utilisation']:.0%} of its limit."
        )
    liquid = limits[limits["limit_name"] == "lcr"].nsmallest(1, "actual").iloc[0]
    messages.append(
        f"Liquidity is {'strong' if liquid['status'] == 'ok' else 'under pressure'}: the lowest "
        f"LCR is {_pct(liquid['actual'])} ({liquid['who']}) against the "
        f"{_limit(liquid['limit_value'])} limit."
    )
    indicators = data.early_warning(con, regime)
    runs = indicators[(indicators["indicator"] == "break_even_run_off")
                      & (indicators["status"] == "alert")]  # fmt: skip
    if not runs.empty:
        weakest = runs.nsmallest(1, "value").iloc[0]
        messages.append(
            f"Early warning: a retail deposit run of {weakest['value']:.1%} would take "
            f"{weakest['who']}'s LCR to its limit (alert below {weakest['threshold']:.0%})."
        )
    outflows = indicators[(indicators["indicator"] == "retail_outflow")
                          & (indicators["status"] == "alert")]  # fmt: skip
    for _, row in outflows.iterrows():
        messages.append(
            f"Early warning: {row['who']} lost {row['value']:.1%} of its "
            f"{row['category'].replace('_', ' ')} in 4 weeks."
        )
    moved = data.limit_movements(con, regime)
    if previous is not None:
        messages.append(
            f"Since {previous:%d %b}: no internal limit changed status."
            if moved.empty
            else f"Since {previous:%d %b}: {len(moved)} limit{'s' if len(moved) > 1 else ''} "
            f"changed status ({', '.join(moved['movement'] + ' ' + moved['who'])})."
        )
    return messages[:limit]


def headroom(con: duckdb.DuckDBPyConnection, regime: str) -> pd.DataFrame:
    """Per limit, the tightest entity or group: the most of its limit used."""
    limits = data.limit_status(con, regime)
    tightest = limits.loc[limits.groupby("limit_name")["utilisation"].idxmax()]
    tightest = tightest.assign(label=tightest["limit_name"].map(LIMIT_LABEL))
    order = list(LIMIT_LABEL)
    tightest = tightest.assign(_order=tightest["limit_name"].map(order.index)).sort_values("_order")
    return tightest[["limit_name", "label", "who", "utilisation", "status", "actual",
                     "limit_value"]].reset_index(drop=True)  # fmt: skip
